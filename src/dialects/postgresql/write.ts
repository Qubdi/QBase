const JSON_BUILDERS =
    /^(?:jsonb?_(?:build_object|build_array|object|array)|to_jsonb?)\s*\(/i;

/** How a stored default is written in a PostgreSQL script. */
export function pgDefault(raw: string, column: Pick<Column, 'type'>): string {
    const text = dropCast(raw.trim());
    if (/^now\(\)$/i.test(text)) return 'CURRENT_TIMESTAMP';
    const typeName = column.type.name.toLowerCase();
    if (
        (typeName === 'json' || typeName === 'jsonb') &&
        JSON_BUILDERS.test(text)
    )
        return text;
    if (/nextval/i.test(text)) return text;
    if (isKnownForm(text) || isFunctionCall(text)) return text;
    if (isKeywordDefault(text) || isQuotedText(text) || isNumberText(text))
        return text;
    return asStringLiteral(text);
}

const SERIAL_BY_BASE: Record<string, string> = {
    integer: 'serial',
    int: 'serial',
    bigint: 'bigserial',
    smallint: 'smallserial',
};

const WITH_LENGTH = new Set([
    'varchar',
    'character varying',
    'char',
    'character',
]);

type UserTypes = Map<string, UserType>;

/**
 * How a column names a user type. A plain lower-case name in the search
 * path stays bare (as the specified samples show); anything PostgreSQL would
 * fold, split or not find is quoted and qualified like CREATE TYPE writes it.
 */
function userTypeReference(type: UserType): string {
    const plain = /^[a-z_][a-z0-9_]*$/.test(type.name);
    const inPath = !type.schema || type.schema === 'public';
    return plain && inPath
        ? type.name
        : qualify(quoteDouble, type.schema, type.name);
}

function typeText(column: Column, userTypes: UserTypes): string {
    const raw = column.type.name;
    const lower = raw.toLowerCase();
    const user = userTypes.get(raw);
    // quoted and qualified exactly as CREATE TYPE writes it
    let base = user ? userTypeReference(user) : lower;
    if (lower === 'user-defined') base = 'jsonb';
    else if (lower === 'array') base = 'text[]';
    const bare = base.replace(/\[\]$/, '');
    if (WITH_LENGTH.has(bare) && typeof column.length === 'number')
        base = `${bare}(${column.length})${base.endsWith('[]') ? '[]' : ''}`;
    else if (
        (bare === 'decimal' || bare === 'numeric') &&
        column.precision !== undefined
    ) {
        const args =
            column.scale !== undefined
                ? `${column.precision}, ${column.scale}`
                : `${column.precision}`;
        base = `${bare}(${args})${base.endsWith('[]') ? '[]' : ''}`;
    }
    if (column.isArray && !base.endsWith('[]')) base += '[]';
    return base;
}

/** How a column names its domain: bare when plain, else quoted. */
function domainReference(name: string): string {
    return /^[a-z_][a-z0-9_]*$/.test(name) ? name : quoteDouble(name);
}

/** Domains the tables use, by name, with the base type of the first column that has each. */
function domainsOf(
    tables: ExportTable[],
    userTypes: UserTypes
): Map<string, string> {
    const out = new Map<string, string>();
    for (const t of tables)
        for (const c of t.columns)
            if (c.domain && !out.has(c.domain) && !userTypes.has(c.type.name))
                out.set(c.domain, typeText(c, userTypes));
    return out;
}

function columnLine(
    column: Column,
    userTypes: UserTypes,
    domains: Map<string, string>
): string {
    const comment = column.comments
        ? linesOf(column.comments)
              .map((l) => `    -- ${l}\n`)
              .join('')
        : '';
    const lowerType = column.type.name.toLowerCase();
    const serial = SERIAL_BY_BASE[lowerType];
    const serialColumn = column.increment && !column.nullable && serial;
    const defaultText = column.default?.trim() ?? '';
    const identity = /identity/i.test(defaultText);

    const type = serialColumn
        ? serial
        : column.domain && domains.has(column.domain)
          ? domainReference(column.domain)
          : typeText(column, userTypes);
    let line = `${quoteDouble(column.name)} ${type}`;
    if (!column.nullable) line += ' NOT NULL';
    if (identity) line += ' GENERATED BY DEFAULT AS IDENTITY';
    if (column.generated) {
        line += ` GENERATED ALWAYS AS (${column.generated.expression}) ${
            column.generated.stored ? 'STORED' : 'VIRTUAL'
        }`;
        if (!column.primaryKey && column.unique) line += ' UNIQUE';
        return `${comment}    ${line}`;
    }
    if (!column.primaryKey && column.unique) line += ' UNIQUE';
    const isSerialType = /^(?:big|small)?serial$/.test(lowerType);
    const skipDefault =
        identity ||
        defaultText === '' ||
        ((serialColumn || isSerialType) && /nextval/i.test(defaultText));
    if (!skipDefault) line += ` DEFAULT ${pgDefault(defaultText, column)}`;
    return `${comment}    ${line}`;
}

function indexName(table: string, key: string): string {
    // a name that already carries the table prefix (read back from a script) is not prefixed twice
    const full = toIdentifier(
        key.startsWith(`${table}_`) ? key : `${table}_${key}`
    );
    return full.length > 60 ? clip(toIdentifier(key), 60) : full;
}

/** One name per key, unique inside its schema (clipped to 60 characters). */
function indexNames(
    table: ExportTable,
    used: Set<string>
): Map<string, string> {
    const out = new Map<string, string>();
    for (const { key } of indexKeys(table, { byColumns: true }))
        out.set(
            key.id,
            claimName(used, indexName(table.entity.name, key.label), 60)
        );
    return out;
}

function indexStatements(
    table: ExportTable,
    qualified: string,
    names: Map<string, string>
): string[] {
    const out: string[] = [];
    for (const { key, columns } of indexKeys(table, { byColumns: true })) {
        const name = names.get(key.id)!;
        if (
            key.distinct &&
            columns.length === 1 &&
            columns[0].unique &&
            !columns[0].primaryKey &&
            !key.where &&
            !key.descending?.length
        )
            continue;
        const method =
            key.algorithm &&
            key.algorithm !== 'btree' &&
            INDEX_METHODS.postgresql.includes(key.algorithm)
                ? ` USING ${key.algorithm.toUpperCase()}`
                : '';
        out.push(
            `CREATE ${key.distinct ? 'UNIQUE ' : ''}INDEX ${quoteDouble(
                name
            )} ON ${qualified}${method} (${commaList(
                columns.map((c) => indexColumnText(key, c, quoteDouble))
            )})${key.where ? ` WHERE ${key.where}` : ''};`
        );
    }
    return sortedStatements(out);
}

function indexComments(
    table: ExportTable,
    names: Map<string, string>
): string[] {
    return indexKeys(table, { byColumns: true })
        .filter(({ key }) => key.note)
        .map(
            ({ key }) =>
                `COMMENT ON INDEX ${quoteDouble(
                    names.get(key.id)!
                )} IS ${sqlString(oneLine(key.note ?? ''))};`
        );
}

function tableText(
    table: ExportTable,
    userTypes: UserTypes,
    names: Map<string, string>,
    domains: Map<string, string>
): string {
    const { entity } = table;
    const qualified = qualify(quoteDouble, entity.schema, entity.name);
    const parts = table.columns.map((c) => columnLine(c, userTypes, domains));
    if (table.primary.length > 0)
        parts.push(
            `    PRIMARY KEY (${commaList(
                table.primary.map((c) => quoteDouble(c.name))
            )})`
        );
    for (const rule of table.rules)
        if (rule.expression.trim())
            parts.push(`    CHECK (${rule.expression})`);

    let text = '';
    if (entity.comments)
        text += linesOf(entity.comments)
            .map((l) => `-- ${l}\n`)
            .join('');
    text += `CREATE TABLE ${qualified} (\n${parts.join(',\n')}\n);`;
    if (entity.comments)
        text += `\nCOMMENT ON TABLE ${qualified} IS ${sqlString(
            oneLine(entity.comments)
        )};`;
    for (const c of table.columns)
        if (c.comments)
            text += `\nCOMMENT ON COLUMN ${qualified}.${quoteDouble(
                c.name
            )} IS ${sqlString(oneLine(c.comments))};`;
    const indexes = indexStatements(table, qualified, names);
    if (indexes.length > 0) text += `\n-- Indexes\n${indexes.join('\n')}`;
    const comments = indexComments(table, names);
    if (comments.length > 0) text += `\n${comments.join('\n')}`;
    return `${text}\n`;
}

function userTypeText(type: UserType): string {
    const name = qualify(quoteDouble, type.schema, type.name);
    if (type.kind === 'enum')
        return `CREATE TYPE ${name} AS ENUM (${commaList(
            (type.values ?? []).map(sqlString)
        )});`;
    return `CREATE TYPE ${name} AS (${commaList(
        (type.members ?? []).map((m) => `${quoteDouble(m.name)} ${m.type}`)
    )});`;
}

function foreignKeyName(fk: ExportForeignKey): string {
    const parts = [
        'fk',
        fk.holder.name,
        ...fk.columns.map((c) => c.name),
        fk.referenced.name,
        ...fk.referencedColumns.map((c) => c.name),
    ];
    return clip(toIdentifier(parts.join('_')), 60);
}

function foreignKeyBlock(keys: ExportForeignKey[]): string {
    // constraint names are unique per holding table
    const used = scopes();
    const bySchema = new Map<string, ExportForeignKey[]>();
    for (const fk of keys) {
        const schema = fk.holder.schema || 'public';
        bySchema.set(schema, [...(bySchema.get(schema) ?? []), fk]);
    }
    const groups = [...bySchema.keys()].sort(byText).map((schema) => {
        const statements = bySchema
            .get(schema)!
            .map(
                (fk) =>
                    `ALTER TABLE ${qualify(
                        quoteDouble,
                        fk.holder.schema,
                        fk.holder.name
                    )} ADD CONSTRAINT ${quoteDouble(
                        claimName(
                            used(
                                `${fk.holder.schema ?? ''}\u0000${fk.holder.name}`
                            ),
                            foreignKeyName(fk),
                            60
                        )
                    )} FOREIGN KEY(${commaList(
                        fk.columns.map((c) => quoteDouble(c.name))
                    )}) REFERENCES ${qualify(
                        quoteDouble,
                        fk.referenced.schema,
                        fk.referenced.name
                    )}(${commaList(
                        fk.referencedColumns.map((c) => quoteDouble(c.name))
                    )});`
            );
        return `-- Schema: ${oneLine(schema)}\n${statements.join('\n')}`;
    });
    return `\n-- Foreign key constraints\n${groups.join('\n\n')}`;
}

/** PostgreSQL script for a design (EXP-013 to EXP-019). */
export function writePostgres(design: Design): string {
    const model = prepareExport(design);
    if (model.tables.length === 0) return '';
    const types = listOf(design.userTypes);
    const enums = types
        .filter((t) => t.kind === 'enum')
        .sort((a, b) => byText(a.name, b.name));
    const composites = types
        .filter((t) => t.kind === 'composite')
        .sort((a, b) => byText(a.name, b.name));
    const userTypeNames: UserTypes = new Map(types.map((t) => [t.name, t]));
    const usedIndexNames = scopes();
    const domains = domainsOf(model.tables, userTypeNames);

    const schemas = firstSeen(
        [
            ...model.tables.map((t) => t.entity.schema),
            ...types.map((t) => t.schema),
        ].filter((s): s is string => !!s)
    );
    const sequences = firstSeen(
        model.tables.flatMap((t) =>
            t.columns.flatMap((c) => {
                const found = /nextval\(\s*'([^']+)'/i.exec(c.default ?? '');
                return found ? [found[1]] : [];
            })
        )
    );

    let out = '';
    if (schemas.length > 0)
        out += `${schemas
            .map((s) => `CREATE SCHEMA IF NOT EXISTS ${quoteDouble(s)};`)
            .join('\n')}\n\n`;
    const typeStatements = [...enums, ...composites].map(userTypeText);
    if (typeStatements.length > 0) out += `${typeStatements.join('\n')}\n\n`;
    if (domains.size > 0)
        out += `${[...domains]
            .map(
                ([name, base]) =>
                    `CREATE DOMAIN ${domainReference(name)} AS ${base};`
            )
            .join('\n')}\n\n`;
    if (sequences.length > 0)
        out += `${sequences
            .map((s) => `CREATE SEQUENCE IF NOT EXISTS ${s};`)
            .join('\n')}\n\n`;
    out += model.tables
        .map((t) =>
            tableText(
                t,
                userTypeNames,
                indexNames(t, usedIndexNames(t.entity.schema ?? '')),
                domains
            )
        )
        .join('\n');
    if (model.foreignKeys.length > 0) out += foreignKeyBlock(model.foreignKeys);
    return out;
}
