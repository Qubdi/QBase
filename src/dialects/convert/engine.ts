type Section =
    | 'Type conversions'
    | 'Default values'
    | 'Auto numbering'
    | 'Constraints'
    | 'Indexes'
    | 'Foreign keys'
    | 'Schemas and views'
    | 'Names';

/** Conversion notes, grouped by section in the order each section is first used. */
class Notes {
    private readonly sections = new Map<Section, string[]>();
    private count = 0;

    add(section: Section, where: string, text: string): void {
        const line = `${where ? `${where}: ` : ''}${text}`.replace(
            /\s*[\r\n]+\s*/g,
            ' '
        );
        const list = this.sections.get(section) ?? [];
        if (list.includes(line)) return;
        list.push(line);
        this.sections.set(section, list);
        this.count++;
    }

    header(from: string, to: string): string {
        const lines = [
            `-- ${from} to ${to} conversion`,
            '-- Generated by QBase',
        ];
        if (this.count > 0) {
            lines.push('--', `-- CONVERSION NOTES (${this.count} items):`);
            for (const [section, items] of this.sections) {
                lines.push('--', `-- ${section}:`);
                for (const item of items) lines.push(`--   - ${item}`);
            }
            lines.push('--');
        }
        return `${lines.join('\n')}\n\n`;
    }
}

const SQLITE_NO_SCHEMA =
    'SQLite has no schemas: table names are prefixed with the schema name';

function schemaStatement(flavour: string, schema: string): string {
    if (flavour === 'postgres')
        return `CREATE SCHEMA IF NOT EXISTS "${schema.replace(/"/g, '""')}";`;
    if (flavour === 'mysql')
        return `CREATE DATABASE IF NOT EXISTS \`${schema.replace(/`/g, '``')}\`;`;
    const text = schema.replace(/'/g, "''");
    return `IF NOT EXISTS (SELECT * FROM sys.schemas WHERE name = '${text}') EXEC('CREATE SCHEMA [${schema.replace(/\]/g, ']]').replace(/'/g, "''")}]');`;
}

interface Prepared {
    column: Column;
    read: NeutralRead;
    neutral: Neutral;
}

/** Converts a design to another dialect's SQL (EXP-006, EXP-037 to EXP-048). */
export function convertDesign(
    design: Design,
    source: Dialect,
    target: Dialect
): { text: string; diagnostics: Diagnostic[] } {
    const tgt = target.sql.target;
    const src = source.sql.source ?? { flavour: 'postgres' as const };
    if (!tgt)
        return {
            text: '',
            diagnostics: [
                {
                    severity: 'error',
                    message: `Conversion to ${target.label} is not supported`,
                },
            ],
        };
    const flavour = tgt.flavour;
    const q = tgt.quote;
    const notes = new Notes();
    const model = prepareExport(design);
    const userTypes = listOf(design.userTypes);

    const sourceLabel = source.id === 'generic' ? 'generic SQL' : source.label;
    if (model.viewCount > 0)
        notes.add(
            'Schemas and views',
            '',
            `${model.viewCount} view${model.viewCount === 1 ? '' : 's'} not exported: only tables are converted`
        );

    const exported = model.tables.filter((t) => {
        if (t.columns.length > 0) return true;
        notes.add(
            'Schemas and views',
            t.entity.name,
            'not exported: the table has no columns'
        );
        return false;
    });
    const nameOf = (t: ExportTable): string =>
        flavour === 'sqlite' &&
        t.entity.schema &&
        t.entity.schema !== src.defaultSchema
            ? `${t.entity.schema}_${t.entity.name}`
            : t.entity.name;
    const qualifiedName = (t: ExportTable['entity']): string => {
        const own = exported.find((e) => e.entity.id === t.id);
        if (flavour === 'sqlite') return q(own ? nameOf(own) : t.name);
        return t.schema && t.schema !== src.defaultSchema
            ? `${q(t.schema)}.${q(t.name)}`
            : q(t.name);
    };

    const schemas = [
        ...new Set(
            exported
                .map((t) => t.entity.schema)
                .filter((s): s is string => !!s && s !== src.defaultSchema)
        ),
    ];
    let schemaText = '';
    if (flavour === 'sqlite') {
        if (schemas.length > 0)
            notes.add('Schemas and views', '', SQLITE_NO_SCHEMA);
    } else if (schemas.length > 0)
        schemaText = `${schemas.map((s) => schemaStatement(flavour, s)).join('\n')}\n\n`;

    // columns that take part in a key are "key sized"
    const keySized = new Set<string>();
    for (const t of exported) {
        t.primary.forEach((c) => keySized.add(c.id));
        t.columns.filter((c) => c.unique).forEach((c) => keySized.add(c.id));
        t.keys.forEach((k) => k.columns.forEach((c) => keySized.add(c.id)));
    }
    model.foreignKeys.forEach((fk) =>
        [...fk.columns, ...fk.referencedColumns].forEach((c) =>
            keySized.add(c.id)
        )
    );

    // read every column once
    const prepared = new Map<string, Prepared>();
    for (const t of exported)
        for (const column of t.columns) {
            const read = readNeutral(column, src.flavour, userTypes);
            prepared.set(column.id, { column, read, neutral: read.neutral });
        }
    // a foreign key column follows the integer it references (EXP-041)
    for (const fk of model.foreignKeys)
        fk.columns.forEach((c, i) => {
            const here = prepared.get(c.id);
            const there = prepared.get(fk.referencedColumns[i].id);
            if (
                !here ||
                !there ||
                here.neutral.kind !== 'int' ||
                there.neutral.kind !== 'int'
            )
                return;
            if (
                here.neutral.bits === there.neutral.bits &&
                !!here.neutral.unsigned === !!there.neutral.unsigned
            )
                return;
            here.neutral = there.neutral;
            notes.add(
                'Type conversions',
                `${fk.holder.name}.${c.name}`,
                `changed to match ${fk.referenced.name}.${fk.referencedColumns[i].name}, which it references`
            );
        });

    const usedIndexNames = new Set<string>();
    const blocks: string[] = [];
    const foreignStatements: string[] = [];
    const sourceIsMysql = src.flavour === 'mysql';

    for (const t of exported) {
        const tableName = nameOf(t);
        const where = (c: Column): string => `${t.entity.name}.${c.name}`;
        const tooLong = (name: string, what: string): void => {
            if (name.length > tgt.identifierLimit)
                notes.add(
                    'Names',
                    name,
                    `${what} name is longer than ${tgt.identifierLimit} characters, the limit of ${target.label}`
                );
        };
        tooLong(tableName, 'table');
        const afterTable: string[] = [];
        const numberedColumns: Column[] = [];

        // auto numbering decisions
        const numberedIds = new Set<string>();
        for (const column of t.columns) {
            const p = prepared.get(column.id)!;
            const wants =
                !!column.increment ||
                !!p.read.numbered ||
                isNumberingMarker(column.default);
            if (!wants) continue;
            let problem: string | undefined;
            if (p.neutral.kind !== 'int') problem = 'not an integer column';
            else if (
                flavour === 'postgres' &&
                ![16, 32, 64].includes(p.neutral.bits)
            )
                problem = 'the integer size is not 16, 32 or 64 bits';
            else if (flavour !== 'postgres' && numberedColumns.length > 0)
                problem = `only one column per table can be numbered in ${target.label}`;
            else if (
                flavour === 'sqlite' &&
                !(t.primary.length === 1 && t.primary[0].id === column.id)
            )
                problem =
                    'only the whole primary key can be numbered in SQLite';
            if (problem)
                notes.add(
                    'Auto numbering',
                    where(column),
                    `${problem}: the column is not numbered`
                );
            else {
                numberedIds.add(column.id);
                numberedColumns.push(column);
            }
        }
        const inlineKey =
            flavour === 'sqlite' && numberedColumns.length === 1
                ? numberedColumns[0]
                : undefined;

        const enumChecks: string[] = [];
        const columnComments: string[] = [];
        const columnLines = t.columns.map((column) => {
            const p = prepared.get(column.id)!;
            const numbered = numberedIds.has(column.id);
            const isKey = keySized.has(column.id);
            let neutral = p.neutral;
            let numberedInt: string | undefined;
            if (numbered && neutral.kind === 'int' && flavour === 'postgres')
                numberedInt =
                    neutral.bits === 16
                        ? 'smallserial'
                        : neutral.bits === 64
                          ? 'bigserial'
                          : 'serial';
            const type = writeNeutral(neutral, flavour, { keySized: isKey });
            tooLong(column.name, 'column');
            if (flavour === 'sqlite' && neutral.kind === 'decimal')
                notes.add(
                    'Type conversions',
                    '',
                    'SQLite has no fixed point type: DECIMAL and NUMERIC columns use NUMERIC affinity'
                );
            for (const n of type.notes)
                notes.add('Type conversions', where(column), n);
            if (p.read.note)
                notes.add('Type conversions', where(column), p.read.note);
            if (neutral.kind === 'array') {
                notes.add(
                    'Type conversions',
                    where(column),
                    `${column.type.name.replace(/\[\]$/, '')} is an array`
                );
                if (flavour !== 'postgres')
                    notes.add(
                        'Type conversions',
                        where(column),
                        'stored as JSON text'
                    );
            }
            if (type.enumValues)
                enumChecks.push(
                    `CHECK (${q(column.name)} IN (${type.enumValues
                        .map(
                            (v) =>
                                `${flavour === 'sqlserver' ? 'N' : ''}'${v.replace(/'/g, "''")}'`
                        )
                        .join(', ')}))`
                );
            neutral = p.neutral;

            const flags: string[] = [];
            const notNull = column.primaryKey || numbered || !column.nullable;
            const typeText = numberedInt ?? type.text;
            let line = `${q(column.name)} ${typeText}`;
            const unique =
                column.unique && !(column.primaryKey && t.primary.length === 1);
            let def: string | undefined;
            if (column.default && column.default.trim() !== '' && !numbered) {
                const d = convertDefault(column.default, neutral, flavour);
                if (d.note) notes.add('Default values', where(column), d.note);
                def = d.text;
            }
            if (flavour === 'sqlserver') {
                if (numbered) flags.push('IDENTITY(1,1)');
                flags.push(notNull ? 'NOT NULL' : 'NULL');
                if (unique) flags.push('UNIQUE');
            } else if (inlineKey === column) {
                line = `${q(column.name)} INTEGER`;
                flags.push('NOT NULL', 'PRIMARY KEY', 'AUTOINCREMENT');
                if (unique) flags.push('UNIQUE');
            } else {
                if (notNull) flags.push('NOT NULL');
                if (numbered && flavour === 'mysql')
                    flags.push('AUTO_INCREMENT');
                if (unique) flags.push('UNIQUE');
            }
            if (def !== undefined) flags.push(`DEFAULT ${def}`);
            if (column.comments && flavour === 'mysql')
                flags.push(
                    `COMMENT '${column.comments.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`
                );
            if (flags.length) line += ` ${flags.join(' ')}`;
            if (column.comments && flavour === 'postgres')
                columnComments.push(
                    `COMMENT ON COLUMN ${qualifiedName(t.entity)}.${q(column.name)} IS '${oneLine(column.comments).replace(/'/g, "''")}';`
                );
            const above =
                column.comments &&
                (flavour === 'sqlserver' || flavour === 'sqlite')
                    ? linesOf(column.comments)
                          .map((l) => `    -- ${l}\n`)
                          .join('')
                    : '';
            return {
                text: `${above}    ${line}`,
                was:
                    p.read.approximate || type.approximate
                        ? ` -- Was: ${column.type.name}`
                        : '',
            };
        });

        const constraints: string[] = [];
        if (t.primary.length > 0 && !inlineKey)
            constraints.push(
                `PRIMARY KEY (${commaList(t.primary.map((c) => q(c.name)))})`
            );
        if (flavour === 'mysql')
            for (const c of numberedColumns) {
                // MySQL needs the numbered column first in some key (error 1075)
                const indexed =
                    t.primary[0]?.id === c.id ||
                    t.keys.some((k) => !k.key.pk && k.columns[0]?.id === c.id);
                if (!indexed) constraints.push(`KEY (${q(c.name)})`);
            }
        constraints.push(...enumChecks);
        for (const rule of t.rules) {
            if (!rule.expression.trim()) continue;
            const r = convertCheck(
                rule.expression,
                t.columns.map((c) => c.name),
                q,
                flavour,
                sourceIsMysql
            );
            if ('text' in r) constraints.push(`CHECK (${r.text})`);
            else {
                notes.add(
                    'Constraints',
                    t.entity.name,
                    `CHECK (${rule.expression}) not created: it uses ${r.reason}`
                );
                afterTable.push(
                    `-- not created (uses ${r.reason}): CHECK (${rule.expression})`
                );
            }
        }

        // foreign keys
        const validFor = (fk: ExportForeignKey): string | undefined => {
            const ref = exported.find((e) => e.entity.id === fk.referenced.id);
            if (!ref) return 'the referenced table is not exported';
            const names = fk.referencedColumns.map((c) => c.id);
            const pk = ref.primary.map((c) => c.id);
            const samePk =
                pk.length === names.length &&
                pk.every((id) => names.includes(id));
            const unique = names.length === 1 && fk.referencedColumns[0].unique;
            const uniqueIndex = ref.keys.some(
                (k) =>
                    k.key.distinct &&
                    k.columns.length === names.length &&
                    k.columns.every((c) => names.includes(c.id))
            );
            if (samePk || unique || uniqueIndex) return undefined;
            const first = fk.referencedColumns[0];
            const refName = `${fk.referenced.name}.${first.name}`;
            return pk.includes(first.id)
                ? `${refName} is only part of a composite key, and no database accepts a foreign key to part of a key`
                : `${refName} is not unique, and no database accepts a foreign key to a column that is not`;
        };
        for (const fk of foreignKeysHeldBy(model, t.entity)) {
            const bad = validFor(fk);
            const cols = commaList(fk.columns.map((c) => q(c.name)));
            const list = `FOREIGN KEY (${cols}) on ${fk.holder.name} -> ${fk.referenced.name}`;
            if (bad) {
                notes.add(
                    'Foreign keys',
                    fk.holder.name,
                    `FOREIGN KEY (${cols}) -> ${fk.referenced.name} not created: ${bad}`
                );
                foreignStatements.push(`-- not created (${bad}): ${list}`);
                continue;
            }
            const ref = `${qualifiedName(fk.referenced)} (${commaList(fk.referencedColumns.map((c) => q(c.name)))})`;
            if (flavour === 'sqlite')
                constraints.push(
                    `FOREIGN KEY (${commaList(fk.columns.map((c) => q(c.name)))}) REFERENCES ${ref}`
                );
            else {
                const base =
                    fk.name ||
                    toIdentifier(
                        `fk_${fk.holder.name}_${fk.columns.map((c) => c.name).join('_')}`
                    );
                const name = clip(base, tgt.identifierLimit);
                if (name !== base)
                    notes.add(
                        'Names',
                        base,
                        `shortened to ${tgt.identifierLimit} characters`
                    );
                foreignStatements.push(
                    `ALTER TABLE ${qualifiedName(fk.holder)} ADD CONSTRAINT ${q(name)} FOREIGN KEY (${commaList(fk.columns.map((c) => q(c.name)))}) REFERENCES ${ref};`
                );
            }
        }

        const body: string[] = [];
        const items = [
            ...columnLines.map((c) => ({ text: c.text, was: c.was })),
            ...constraints.map((c) => ({ text: `    ${c}`, was: '' })),
        ];
        items.forEach((item, i) =>
            body.push(
                `${item.text}${i < items.length - 1 ? ',' : ''}${item.was}`
            )
        );
        let head = '';
        if (
            t.entity.comments &&
            (flavour === 'sqlserver' || flavour === 'sqlite')
        )
            head = linesOf(t.entity.comments)
                .map((l) => `-- ${l}\n`)
                .join('');
        const tableComment =
            t.entity.comments && flavour === 'mysql'
                ? ` COMMENT='${t.entity.comments.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`
                : '';
        let text = `${head}CREATE TABLE ${flavour === 'sqlite' ? q(tableName) : qualifiedName(t.entity)} (\n${body.join('\n')}\n)${tableComment};`;
        if (t.entity.comments && flavour === 'postgres')
            text += `\nCOMMENT ON TABLE ${qualifiedName(t.entity)} IS '${oneLine(t.entity.comments).replace(/'/g, "''")}';`;
        if (columnComments.length) text += `\n${columnComments.join('\n')}`;
        if (afterTable.length) text += `\n${afterTable.join('\n')}`;

        // indexes
        const statements: string[] = [];
        for (const { key, columns } of t.keys) {
            if (
                key.pk ||
                columns.length === 0 ||
                coversPrimaryKey(t, { key, columns })
            )
                continue;
            const stored =
                key.label ||
                `idx_${t.entity.name}_${columns.map((c) => c.name).join('_')}`;
            let name = stored;
            for (let n = 2; usedIndexNames.has(name); n++)
                name = `${stored}_${t.entity.name}_${n}`;
            if (name.length > tgt.identifierLimit) {
                notes.add(
                    'Names',
                    stored,
                    `index name shortened to ${tgt.identifierLimit} characters`
                );
                name = name.slice(0, tgt.identifierLimit);
            }
            usedIndexNames.add(name);
            const method = key.algorithm;
            if (
                method &&
                !['btree', 'index'].includes(method) &&
                !(
                    flavour === 'sqlserver' &&
                    (method === 'clustered' || method === 'nonclustered')
                )
            )
                notes.add(
                    'Indexes',
                    `${t.entity.name}.${stored}`,
                    `${method} index created as a regular index`
                );
            statements.push(
                `CREATE ${key.distinct ? 'UNIQUE ' : ''}INDEX ${q(name)} ON ${qualifiedName(t.entity)} (${commaList(columns.map((c) => q(c.name)))});`
            );
        }
        if (statements.length)
            text += `\n\n-- Indexes\n${sortedStatements(statements).join('\n')}`;
        blocks.push(text);
    }

    if (blocks.length === 0)
        return {
            text: '',
            diagnostics: [{ severity: 'error', message: 'Nothing to export' }],
        };
    let text =
        notes.header(sourceLabel, target.label) +
        schemaText +
        blocks.join('\n\n');
    if (foreignStatements.length)
        text += `\n\n-- Foreign key constraints\n${foreignStatements.join('\n')}`;
    return { text: `${text}\n`, diagnostics: [] };
}
