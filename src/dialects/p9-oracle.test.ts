const ORACLE_SCRIPT = `
CREATE TABLE FINANCE.ACCOUNTS (
  ID NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NAME VARCHAR2(100 CHAR) NOT NULL,
  BALANCE NUMBER(12,2) DEFAULT 0,
  OPENED TIMESTAMP(6) WITH LOCAL TIME ZONE,
  NOTE CLOB,
  CONSTRAINT ACCOUNTS_PK PRIMARY KEY (ID)
);
CREATE TABLE FINANCE.ENTRIES (
  ID NUMBER(10) NOT NULL,
  ACCOUNT_ID NUMBER(10) NOT NULL,
  AMOUNT NUMBER(12,2),
  CONSTRAINT ENTRIES_PK PRIMARY KEY (ID),
  CONSTRAINT ENTRIES_ACC_FK FOREIGN KEY (ACCOUNT_ID) REFERENCES FINANCE.ACCOUNTS (ID)
);
CREATE INDEX ENTRIES_ACC_IX ON FINANCE.ENTRIES (ACCOUNT_ID);
COMMENT ON TABLE FINANCE.ACCOUNTS IS 'Customer accounts';
COMMENT ON COLUMN FINANCE.ACCOUNTS.NAME IS 'Display name';
`;

const named = (d: Design, name: string) =>
    listOf(d.entities).find((e) => e.name === name)!;
const columnsOf = (d: Design, name: string) =>
    named(d, name).columnIds.map((id) => d.columns[id]);

describe('EXP-008 Oracle model facts (editor 14)', () => {
    it('schema, array, check and default-schema rules', () => {
        expect(traitsOf('oracle')).toMatchObject({
            hasSchemas: true,
            hasArrays: false,
            hasUserTypes: false,
            defaultColumnType: 'number',
        });
        expect(traitsOf('oracle').defaultSchema).toBeUndefined();
    });
    it('has its own type list and capabilities', () => {
        const oracle = dialectFor('oracle');
        expect(oracle.types).toContain('varchar2');
        expect(oracle.types).toContain('timestamp with time zone');
        expect(oracle.types).toHaveLength(23);
        expect(oracle.capabilities.nativeComments).toBe(true);
    });
    it('an Oracle design is edited like any other', () => {
        for (const type of ['oracle'] as const) {
            const next = applyOk(blank(type), {
                type: 'design.rename',
                name: 'x',
            });
            expect(next.design.name).toBe('x');
        }
    });
});

describe('IMP-001 IMP-008 Oracle SQL import', () => {
    it('reads types, sizes, identity, keys, comments and indexes', () => {
        const r = importSql(ORACLE_SCRIPT, 'oracle');
        expect(r.diagnostics.filter((d) => d.severity === 'error')).toEqual([]);
        const d = r.design!;
        expect(d.databaseType).toBe('oracle');
        expect(r.counts).toMatchObject({ tables: 2, relationships: 1 });
        const [id, name, balance, opened] = columnsOf(d, 'ACCOUNTS');
        expect(id).toMatchObject({
            primaryKey: true,
            increment: true,
            precision: 10,
        });
        expect(name.type.name).toBe('varchar2');
        expect(name.length).toBe(100);
        expect(name.comments).toBe('Display name');
        expect(balance).toMatchObject({ precision: 12, scale: 2 });
        expect(opened.type.name).toBe('timestamp with local time zone');
        expect(named(d, 'ACCOUNTS').schema).toBe('FINANCE');
        expect(named(d, 'ACCOUNTS').comments).toBe('Customer accounts');
        expect(named(d, 'ENTRIES').keyIds.length).toBeGreaterThan(0);
    });
    it('warns about foreign syntax with the Oracle way to say it', () => {
        const r = importSql(
            'CREATE TABLE a (\n id SERIAL,\n b TINYINT,\n c UNIQUEIDENTIFIER\n);',
            'oracle'
        );
        const text = r.diagnostics.map((d) => d.message).join('\n');
        expect(text).toContain('SERIAL is PostgreSQL syntax');
        expect(text).toContain('use NUMBER(3)');
        expect(text).toContain('use RAW(16)');
    });
});

describe('EXP-008 SQL export for Oracle', () => {
    const oracle = importSql(ORACLE_SCRIPT, 'oracle').design!;

    it('an Oracle diagram writes its own Oracle script', () => {
        const { text } = exportSql(oracle, 'oracle');
        expect(text).not.toContain('WARNING');
        expect(text).not.toContain('CREATE SCHEMA');
        expect(text).toContain('CREATE TABLE "FINANCE"."ACCOUNTS" (');
        expect(text).toContain(
            '"ID" number(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL'
        );
        expect(text).toContain('"NAME" varchar2(100) NOT NULL');
        expect(text).toContain('"BALANCE" number(12, 2) DEFAULT 0');
        expect(text).toContain('PRIMARY KEY ("ID")');
        expect(text).toContain(
            `COMMENT ON TABLE "FINANCE"."ACCOUNTS" IS 'Customer accounts';`
        );
        expect(text).toContain(
            'CREATE INDEX "ENTRIES_ACC_IX" ON "FINANCE"."ENTRIES" ("ACCOUNT_ID");'
        );
        expect(text).toContain(
            'ALTER TABLE "FINANCE"."ENTRIES" ADD CONSTRAINT'
        );
        expect(text).toContain('REFERENCES "FINANCE"."ACCOUNTS" ("ID")');
    });
    it('the script reads back as the same tables (round trip)', () => {
        const { text } = exportSql(oracle, 'oracle');
        const again = importSql(text, 'oracle');
        expect(again.diagnostics.filter((d) => d.severity === 'error')).toEqual(
            []
        );
        expect(again.counts).toMatchObject({ tables: 2, relationships: 1 });
        expect(columnsOf(again.design!, 'ACCOUNTS').map((c) => c.name)).toEqual(
            columnsOf(oracle, 'ACCOUNTS').map((c) => c.name)
        );
        expect(columnsOf(again.design!, 'ACCOUNTS')[1].length).toBe(100);
    });
    it('Oracle converts to another database', () => {
        const { text } = exportSql(oracle, 'postgresql');
        expect(text).toMatch(/^-- Oracle to PostgreSQL conversion\n/);
        expect(text).toContain('CREATE TABLE "FINANCE"."ACCOUNTS"');
    });
    it('another database converts to Oracle', () => {
        const { text } = exportSql(sampleS1('postgresql'), 'oracle');
        expect(text).toMatch(/^-- PostgreSQL to Oracle conversion\n/);
        expect(text).toContain('CREATE TABLE');
    });
    it('views are not written and are reported', () => {
        const withView = importSql(
            `${ORACLE_SCRIPT}\nCREATE VIEW V1 AS SELECT ID FROM FINANCE.ACCOUNTS;`,
            'oracle'
        ).design!;
        const r = exportSql(withView, 'postgresql');
        expect(r.text).not.toContain('V1');
        expect(r.text).toContain('1 view not exported');
    });
    it('an empty Oracle diagram gives the nothing-to-export error', () => {
        expect(
            exportSql(blank('oracle'), 'oracle').diagnostics[0].message
        ).toBe('Nothing to export');
    });
});

describe('IMP-056 database-metadata import accepts Oracle', () => {
    const meta = (version: string): DatabaseMetadata => ({
        database_name: 'ledger',
        version,
        tables: [
            { schema: 'FINANCE', table: 'ACCOUNTS' },
            { schema: 'FINANCE', table: 'ENTRIES' },
        ],
        views: [],
        columns: [
            {
                schema: 'FINANCE',
                table: 'ACCOUNTS',
                name: 'ID',
                type: 'number',
                ordinal_position: 1,
                nullable: false,
                precision: { precision: 10, scale: 0 },
                is_identity: true,
            },
            {
                schema: 'FINANCE',
                table: 'ACCOUNTS',
                name: 'NAME',
                type: 'varchar2',
                ordinal_position: 2,
                nullable: false,
                character_maximum_length: '100',
            },
            {
                schema: 'FINANCE',
                table: 'ENTRIES',
                name: 'ACCOUNT_ID',
                type: 'number',
                ordinal_position: 1,
                nullable: false,
            },
        ],
        pk_info: [
            {
                schema: 'FINANCE',
                table: 'ACCOUNTS',
                column: 'ID',
                pk_def: 'PRIMARY KEY',
            },
        ],
        fk_info: [
            {
                schema: 'FINANCE',
                table: 'ENTRIES',
                column: 'ACCOUNT_ID',
                foreign_key_name: 'FK1',
                reference_schema: 'FINANCE',
                reference_table: 'ACCOUNTS',
                reference_column: 'ID',
                fk_def: 'FOREIGN KEY',
            },
        ],
        indexes: [],
    });
    it.each(['oracle'] as const)(
        '%s builds a design of its own type',
        (type) => {
            const r = loadFromDatabaseMetadata({
                databaseType: type,
                databaseMetadata: meta('x'),
            });
            expect(r.design.databaseType).toBe(type);
            expect(r.design.entities.order).toHaveLength(2);
            expect(r.design.links.order).toHaveLength(1);
            expect(columnsOf(r.design, 'ACCOUNTS')[1]).toMatchObject({
                length: 100,
            });
        }
    );
    it('Oracle has a script that returns one metadata cell with the contract keys', () => {
        for (const type of ['oracle'] as const) {
            const script = metadataScriptFor(type)!;
            for (const key of [
                'database_name',
                'version',
                'tables',
                'views',
                'columns',
                'pk_info',
                'fk_info',
                'indexes',
                'metadata_json_to_import',
            ])
                expect(script, `${type} ${key}`).toContain(key);
        }
    });
});

describe('IMP-045 DBML for Oracle', () => {
    it.each(['oracle'] as const)('%s reads and writes DBML', (type) => {
        const text = `Table accounts {\n  id integer [pk]\n  name varchar(40) [not null]\n}\nTable entries {\n  id integer [pk]\n  account_id integer [ref: > accounts.id]\n}\n`;
        const r = importDbml(text, type);
        expect(r.design?.databaseType).toBe(type);
        expect(r.counts).toMatchObject({ tables: 2, relationships: 1 });
        const out = exportDbml(r.design!);
        expect(out.text).toMatch(/Table ("default"\.)?"accounts"/);
        expect(out.text).toContain('account_id');
    });
});
