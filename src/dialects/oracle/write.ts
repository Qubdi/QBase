import type { Column } from '@/core/model/column';
import type { Design } from '@/core/model/design';
import { sizeSuffix } from '@/core/model/type-suffix';
import {
    asStringLiteral,
    isFunctionCall,
    isKeywordDefault,
    isNumberText,
    isNumberingMarker,
    isQuotedText,
    unwrapOnce,
} from '../shared/defaults';
import type { ExportForeignKey, ExportTable } from '../shared/export-model';
import {
    indexColumnText,
    indexKeys,
    prepareExport,
    sortedStatements,
} from '../shared/export-model';
import {
    claimName,
    commaList,
    linesOf,
    oneLine,
    qualify,
    quoteDouble,
    scopes,
    sqlString,
    toIdentifier,
} from '../shared/text';

/** Identifiers may be 128 bytes long from Oracle 12.2. */
const NAME_LIMIT = 128;

/** Type name as stored plus its arguments. */
export function oracleType(column: Column): string {
    const name = column.type.name;
    return /\(/.test(name) ? name : `${name}${sizeSuffix(column)}`;
}

/** A default as Oracle takes it: expressions and literals as written, other text quoted. */
export function oracleDefault(raw: string): string {
    let text = raw.trim();
    for (
        let inner = unwrapOnce(text);
        inner !== undefined;
        inner = unwrapOnce(text)
    )
        text = inner;
    if (
        isQuotedText(text) ||
        isFunctionCall(text) ||
        isKeywordDefault(text) ||
        isNumberText(text) ||
        /^(?:sysdate|systimestamp)$/i.test(text)
    )
        return text;
    return asStringLiteral(text);
}

function columnLine(column: Column): string {
    const text = column.default?.trim() ?? '';
    const numbered = column.increment || isNumberingMarker(text);
    let line = `${quoteDouble(column.name)} ${oracleType(column)}`;
    // the default comes before the constraints in Oracle
    if (numbered) line += ' GENERATED BY DEFAULT AS IDENTITY';
    else if (text !== '') line += ` DEFAULT ${oracleDefault(text)}`;
    if (!column.nullable) line += ' NOT NULL';
    if (!column.primaryKey && column.unique) line += ' UNIQUE';
    return `    ${line}`;
}

function indexStatements(
    table: ExportTable,
    qualified: string,
    used: Set<string>
): string[] {
    const out = indexKeys(table, { byColumns: true }).map(
        ({ key, columns }) => {
            const base = toIdentifier(
                key.label.startsWith(`${table.entity.name}_`)
                    ? key.label
                    : `${table.entity.name}_${key.label}`
            );
            const name = claimName(used, base, NAME_LIMIT);
            const left = key.where
                ? ` -- ${oneLine(`WHERE ${key.where}`)} left out: Oracle has no partial indexes`
                : '';
            return `CREATE ${key.distinct ? 'UNIQUE ' : ''}INDEX ${quoteDouble(
                name
            )} ON ${qualified} (${commaList(
                columns.map((c) => indexColumnText(key, c, quoteDouble))
            )});${left}`;
        }
    );
    return sortedStatements(out);
}

function tableText(table: ExportTable, indexNames: Set<string>): string {
    const { entity } = table;
    const qualified = qualify(quoteDouble, entity.schema, entity.name);
    const parts = table.columns.map(columnLine);
    if (table.primary.length > 0)
        parts.push(
            `    PRIMARY KEY (${commaList(
                table.primary.map((c) => quoteDouble(c.name))
            )})`
        );
    for (const rule of table.rules)
        if (rule.expression.trim())
            parts.push(`    CHECK (${rule.expression})`);
    let text = '';
    if (entity.comments)
        text += linesOf(entity.comments)
            .map((l) => `-- ${l}\n`)
            .join('');
    text += `CREATE TABLE ${qualified} (\n${parts.join(',\n')}\n);`;
    if (entity.comments)
        text += `\nCOMMENT ON TABLE ${qualified} IS ${sqlString(oneLine(entity.comments))};`;
    for (const c of table.columns)
        if (c.comments)
            text += `\nCOMMENT ON COLUMN ${qualified}.${quoteDouble(c.name)} IS ${sqlString(oneLine(c.comments))};`;
    const indexes = indexStatements(table, qualified, indexNames);
    if (indexes.length > 0) text += `\n-- Indexes\n${indexes.join('\n')}`;
    return `${text}\n`;
}

function foreignKeyBlock(keys: ExportForeignKey[]): string {
    // constraint names are unique per schema
    const used = scopes();
    const statements = keys.map((fk) => {
        const name = claimName(
            used(fk.holder.schema ?? ''),
            fk.name ||
                toIdentifier(
                    `fk_${fk.holder.name}_${fk.columns.map((c) => c.name).join('_')}`
                ),
            NAME_LIMIT
        );
        return `ALTER TABLE ${qualify(
            quoteDouble,
            fk.holder.schema,
            fk.holder.name
        )} ADD CONSTRAINT ${quoteDouble(name)} FOREIGN KEY (${commaList(
            fk.columns.map((c) => quoteDouble(c.name))
        )}) REFERENCES ${qualify(
            quoteDouble,
            fk.referenced.schema,
            fk.referenced.name
        )} (${commaList(fk.referencedColumns.map((c) => quoteDouble(c.name)))});`;
    });
    return `\n-- Foreign key constraints\n${statements.join('\n')}`;
}

/**
 * Oracle script for a design (12c and later). Types are written as stored, a
 * numbered column is `GENERATED BY DEFAULT AS IDENTITY`. Schemas are users, so
 * no CREATE statement is written for them.
 */
export function writeOracle(design: Design): string {
    const model = prepareExport(design);
    if (model.tables.length === 0) return '';
    const used = scopes();
    let out = model.tables
        .map((t) => tableText(t, used(t.entity.schema ?? '')))
        .join('\n');
    if (model.foreignKeys.length > 0) out += foreignKeyBlock(model.foreignKeys);
    return out;
}
