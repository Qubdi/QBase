import { makeReader } from '../shared/make-reader';
import type { ReaderProfile } from '../shared/profile';
import type { ValidationRules } from '../shared/validate';

const PROFILE: ReaderProfile = {
    lex: {
        identifierQuotes: ['"'],
        hashComments: false,
        dollarStrings: false,
        backslashEscapes: false,
    },
    goBatches: false,
    arrayTypes: false,
    inlineReferencesAreErrors: false,
    typeSynonyms: {},
    detailedSkips: false,
    viewColumnType: 'varchar2',
};

/** Foreign syntax the Oracle reader warns about, each with the Oracle way to say it. */
const RULES: ValidationRules = {
    semicolonWarning: false,
    lineRules: [
        {
            pattern: /\bAUTO_INCREMENT\b/i,
            message:
                'AUTO_INCREMENT is MySQL syntax, use GENERATED BY DEFAULT AS IDENTITY',
        },
        {
            pattern: /\bSERIAL\b/i,
            message:
                'SERIAL is PostgreSQL syntax, use NUMBER GENERATED BY DEFAULT AS IDENTITY',
        },
        {
            pattern: /\bIDENTITY\s*\(\s*\d+\s*,\s*\d+\s*\)/i,
            message:
                'IDENTITY(a,b) is SQL Server syntax, use GENERATED BY DEFAULT AS IDENTITY',
        },
        {
            pattern: /\bTINYINT\b/i,
            message: 'TINYINT is not an Oracle type, use NUMBER(3)',
        },
        {
            pattern: /\bMEDIUMINT\b/i,
            message: 'MEDIUMINT is not an Oracle type, use NUMBER(7)',
        },
        {
            pattern: /\bN?VARCHAR\s*\(\s*max\s*\)/i,
            message:
                'VARCHAR(max) is SQL Server syntax, use VARCHAR2(4000) or CLOB',
        },
        {
            pattern: /\bUNIQUEIDENTIFIER\b/i,
            message: 'UNIQUEIDENTIFIER is SQL Server syntax, use RAW(16)',
        },
        {
            pattern: /\bDATETIME2\b/i,
            message: 'DATETIME2 is SQL Server syntax, use TIMESTAMP',
        },
        {
            pattern: /\bJSONB\b/i,
            message: 'JSONB is PostgreSQL syntax, use JSON or CLOB',
        },
        {
            pattern: /::/,
            message: 'the :: cast is PostgreSQL syntax, use CAST(x AS type)',
        },
    ],
};

export const readOracle = makeReader(PROFILE, RULES);
