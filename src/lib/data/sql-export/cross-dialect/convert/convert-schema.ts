/**
 * Deterministic conversion of a diagram from one database's types and syntax
 * to another's. Anything that has no safe equivalent is left out of the
 * statements and reported in comments, never guessed at.
 */

import { DatabaseType } from '@/lib/domain/database-type';
import type { Diagram } from '@/lib/domain/diagram';
import type { DBField } from '@/lib/domain/db-field';
import type { DBTable } from '@/lib/domain/db-table';
import { escapeSQLComment } from '../common';
import {
    collectForeignKeys,
    sameSet,
    type ForeignKey,
} from '../../foreign-keys';
import {
    parseSourceType,
    sourceDialectOf,
    targetDialectOf,
    type Canon,
    type SourceDialect,
    type TargetDialect,
} from './canonical';
import { convertCheck } from './checks';
import { parseDefault, renderDefault } from './defaults';
import { renderType, type RenderedType } from './render-type';

export const DATABASE_LABEL: Record<DatabaseType, string> = {
    [DatabaseType.POSTGRESQL]: 'PostgreSQL',
    [DatabaseType.COCKROACHDB]: 'CockroachDB',
    [DatabaseType.MYSQL]: 'MySQL',
    [DatabaseType.MARIADB]: 'MariaDB',
    [DatabaseType.SQL_SERVER]: 'SQL Server',
    [DatabaseType.SQLITE]: 'SQLite',
    [DatabaseType.ORACLE]: 'Oracle',
    [DatabaseType.CLICKHOUSE]: 'ClickHouse',
    [DatabaseType.GENERIC]: 'generic SQL',
};

/** the longest name each database accepts */
const MAX_NAME: Record<TargetDialect, number> = {
    postgresql: 63,
    mysql: 64,
    sqlserver: 128,
    sqlite: Number.POSITIVE_INFINITY,
};

const DEFAULT_SCHEMA: Record<string, string> = {
    postgresql: 'public',
    sqlserver: 'dbo',
};

const SECTION = {
    type: 'Type conversions',
    default: 'Default values',
    auto: 'Auto numbering',
    constraint: 'Constraints',
    index: 'Indexes',
    key: 'Foreign keys',
    schema: 'Schemas and views',
    names: 'Names',
} as const;
type Section = (typeof SECTION)[keyof typeof SECTION];

class Notes {
    private items: Array<{ section: Section; where?: string; text: string }> =
        [];
    private seen = new Set<string>();

    add(section: Section, where: string | undefined, text: string) {
        const key = `${section}|${where ?? ''}|${text}`;
        if (this.seen.has(key)) return;
        this.seen.add(key);
        this.items.push({ section, where, text });
    }

    get size() {
        return this.items.length;
    }

    header(source: DatabaseType, target: DatabaseType): string {
        const title = `-- ${DATABASE_LABEL[source]} to ${DATABASE_LABEL[target]} conversion\n-- Generated by QBase\n`;
        if (this.items.length === 0) return `${title}\n`;
        let out = `${title}--\n-- CONVERSION NOTES (${this.items.length} items):\n`;
        const sections = [...new Set(this.items.map((i) => i.section))];
        for (const section of sections) {
            out += `--\n-- ${section}:\n`;
            for (const item of this.items.filter(
                (i) => i.section === section
            )) {
                out += `--   - ${item.where ? `${item.where}: ` : ''}${oneLine(item.text)}\n`;
            }
        }
        return `${out}--\n\n`;
    }
}

const oneLine = (s: string) => s.replace(/\s*[\r\n]+\s*/g, ' ');

const quote = (target: TargetDialect, name: string): string => {
    switch (target) {
        case 'mysql':
            return `\`${name.replace(/`/g, '``')}\``;
        case 'sqlserver':
            return `[${name.replace(/]/g, ']]')}]`;
        default:
            return `"${name.replace(/"/g, '""')}"`;
    }
};

const stringLiteral = (
    target: TargetDialect,
    value: string,
    unicode = false
): string => {
    if (target === 'mysql')
        return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
    const body = `'${value.replace(/'/g, "''")}'`;
    return target === 'sqlserver' && unicode ? `N${body}` : body;
};

interface Column {
    field: DBField;
    canon: Canon;
    auto: boolean;
    typeNote?: string;
}

export interface ConvertOptions {
    diagram: Diagram;
    targetDatabaseType: DatabaseType;
    onlyRelationships?: boolean;
}

/** True when the diagram's database and the target both have a converter. */
export const canConvert = (
    sourceType: DatabaseType,
    targetType: DatabaseType
): boolean =>
    sourceDialectOf(sourceType) !== null &&
    targetDialectOf(targetType) !== null;

export function convertDiagram({
    diagram,
    targetDatabaseType,
    onlyRelationships = false,
}: ConvertOptions): string {
    const source = sourceDialectOf(diagram.databaseType);
    const target = targetDialectOf(targetDatabaseType);
    if (!source || !target || !diagram.tables) return '';
    return convert(
        diagram,
        diagram.tables,
        source,
        target,
        targetDatabaseType,
        onlyRelationships
    );
}

function convert(
    diagram: Diagram,
    allTables: DBTable[],
    source: SourceDialect,
    target: TargetDialect,
    targetDatabaseType: DatabaseType,
    onlyRelationships: boolean
): string {
    const notes = new Notes();
    const customTypes = diagram.customTypes ?? [];
    const tables = allTables.filter((t) => !t.isView);
    const views = allTables.length - tables.length;
    if (views > 0) {
        notes.add(
            SECTION.schema,
            undefined,
            `${views} view${views === 1 ? '' : 's'} not exported: only tables are converted`
        );
    }

    // --- the columns, in the neutral form
    const columns = new Map<string, Column>();
    for (const table of tables) {
        for (const field of table.fields) {
            const parsed = parseSourceType(field, source, customTypes);
            const def = field.default ? parseDefault(field.default) : undefined;
            columns.set(field.id, {
                field,
                canon: parsed.canon,
                auto: !!(
                    parsed.auto ||
                    field.increment ||
                    def?.kind === 'auto'
                ),
                typeNote: parsed.note,
            });
        }
    }

    // --- foreign keys, and the columns that must therefore be key-sized
    const foreignKeys = collectForeignKeys({
        tables,
        relationships: diagram.relationships,
        verifyReferences: true,
    });
    const keyFieldIds = new Set<string>();
    for (const table of tables) {
        for (const f of table.fields) {
            if (f.primaryKey || f.unique) keyFieldIds.add(f.id);
        }
        for (const ix of table.indexes)
            ix.fieldIds.forEach((id) => keyFieldIds.add(id));
    }
    for (const k of foreignKeys) {
        [...k.fkFields, ...k.refFields].forEach((f) => keyFieldIds.add(f.id));
    }

    // a key column takes the size of the column it points at
    for (const k of foreignKeys) {
        k.fkFields.forEach((fkField, i) => {
            const fk = columns.get(fkField.id);
            const ref = columns.get(k.refFields[i].id);
            if (
                !fk ||
                !ref ||
                fk.canon.kind !== 'int' ||
                ref.canon.kind !== 'int'
            )
                return;
            if (
                fk.canon.bits !== ref.canon.bits ||
                !!fk.canon.unsigned !== !!ref.canon.unsigned
            ) {
                fk.canon = ref.canon;
                notes.add(
                    SECTION.type,
                    `${k.fkTable.name}.${fkField.name}`,
                    `changed to match ${k.refTable.name}.${k.refFields[i].name}, which it references`
                );
            }
        });
    }

    // --- names
    const defaultSchema = DEFAULT_SCHEMA[source];
    const schemaOf = (t: DBTable): string | undefined =>
        t.schema && t.schema !== defaultSchema ? t.schema : undefined;
    const tableRef = (t: DBTable): string => {
        const schema = schemaOf(t);
        if (target === 'sqlite') {
            return quote(target, schema ? `${schema}_${t.name}` : t.name);
        }
        return schema
            ? `${quote(target, schema)}.${quote(target, t.name)}`
            : quote(target, t.name);
    };
    const used = new Set<string>();
    const unique = (base: string, suffixSource = ''): string => {
        const max = MAX_NAME[target];
        const fit = (name: string, tail = '') =>
            (name.length + tail.length > max
                ? name.slice(0, max - tail.length)
                : name) + tail;
        let name = fit(base);
        for (let n = 2; used.has(name.toLowerCase()); n++) {
            name = fit(base, `${suffixSource}_${n}`);
        }
        used.add(name.toLowerCase());
        return name;
    };

    const longest = MAX_NAME[target];
    const tooLong = (name: string) => name.length > longest;
    const lengthNote = (where: string, name: string) =>
        notes.add(
            SECTION.names,
            where,
            target === 'postgresql'
                ? `the name is ${name.length} characters and PostgreSQL shortens it to ${longest}, which can make two names the same`
                : `the name is ${name.length} characters, longer than the ${longest} ${DATABASE_LABEL[targetDatabaseType]} allows`
        );
    for (const table of tables) {
        if (tooLong(table.name)) lengthNote(table.name, table.name);
        for (const f of table.fields) {
            if (tooLong(f.name)) lengthNote(`${table.name}.${f.name}`, f.name);
        }
    }

    const schemas = [
        ...new Set(tables.map(schemaOf).filter((s): s is string => !!s)),
    ];
    if (target === 'sqlite' && schemas.length > 0) {
        notes.add(
            SECTION.schema,
            undefined,
            'SQLite has no schemas: table names are prefixed with the schema name'
        );
    }

    // --- foreign keys by table, for SQLite, which can only declare them inside CREATE TABLE
    const fkSql = (k: ForeignKey, inline: boolean): string => {
        const cols = (fs: DBField[]) =>
            fs.map((f) => quote(target, f.name)).join(', ');
        const body = `FOREIGN KEY (${cols(k.fkFields)}) REFERENCES ${tableRef(k.refTable)} (${cols(k.refFields)})`;
        if (inline) return body;
        const name = unique(
            k.name ||
                `fk_${k.fkTable.name}_${k.fkFields.map((f) => f.name).join('_')}`
        );
        return `ALTER TABLE ${tableRef(k.fkTable)} ADD CONSTRAINT ${quote(target, name)} ${body};`;
    };
    const keysUsable = foreignKeys.filter((k) => !k.problem);
    for (const k of foreignKeys.filter((x) => x.problem)) {
        notes.add(
            SECTION.key,
            `${k.fkTable.name}.${k.fkFields.map((f) => f.name).join(', ')}`,
            `foreign key to ${k.refTable.name} not created: ${k.problem}`
        );
    }

    let sql = '';
    const finish = () =>
        `${notes.header(diagram.databaseType, targetDatabaseType)}${sql}`;

    if (!onlyRelationships) {
        for (const schema of schemas) {
            switch (target) {
                case 'postgresql':
                    sql += `CREATE SCHEMA IF NOT EXISTS ${quote(target, schema)};\n`;
                    break;
                case 'mysql':
                    sql += `CREATE DATABASE IF NOT EXISTS ${quote(target, schema)};\n`;
                    break;
                case 'sqlserver':
                    sql += `IF NOT EXISTS (SELECT * FROM sys.schemas WHERE name = ${stringLiteral(target, schema)}) EXEC(${stringLiteral(target, `CREATE SCHEMA ${quote(target, schema)}`)});\n`;
                    break;
                case 'sqlite':
                    break;
            }
        }
        if (schemas.length > 0 && target !== 'sqlite') sql += '\n';

        const tableBlocks: string[] = [];
        for (const table of tables) {
            const block = convertTable(table);
            if (block) tableBlocks.push(block);
        }
        sql += tableBlocks.join('\n');
    }

    if (target !== 'sqlite') {
        const statements = keysUsable.map((k) => fkSql(k, false));
        const skipped = foreignKeys
            .filter((k) => k.problem)
            .map(
                (k) =>
                    `-- not created (${k.problem}): FOREIGN KEY (${k.fkFields.map((f) => f.name).join(', ')}) on ${k.fkTable.name} -> ${k.refTable.name}`
            );
        const all = [...statements, ...skipped];
        if (all.length > 0) {
            sql += `${sql && !sql.endsWith('\n') ? '\n' : ''}\n-- Foreign key constraints\n${all.join('\n')}\n`;
        }
    }
    return finish();

    // ---------------------------------------------------------------- tables

    function convertTable(table: DBTable): string {
        const where = (f?: DBField) =>
            f ? `${table.name}.${f.name}` : table.name;
        if (table.fields.length === 0) {
            notes.add(
                SECTION.schema,
                table.name,
                'not exported: the table has no columns'
            );
            return '';
        }
        const pk = table.fields.filter((f) => f.primaryKey);
        const pkIds = pk.map((f) => f.id);
        let autoUsed = false;

        interface Item {
            before?: string;
            text: string;
            comment?: string;
        }
        const items: Item[] = [];
        const constraints: Item[] = [];
        const after: string[] = [];
        const columnComments: string[] = [];
        const enumChecks: string[] = [];
        const columnTypes = new Map<string, string>();
        let sqliteInlinePk = false;

        // SQLite can only number a lone INTEGER primary key, inline
        const sqliteAutoField =
            target === 'sqlite' &&
            pk.length === 1 &&
            columns.get(pk[0].id)?.auto
                ? pk[0]
                : undefined;

        for (const field of table.fields) {
            const col = columns.get(field.id)!;
            const isKey = keyFieldIds.has(field.id);
            const rendered: RenderedType = renderType(target, col.canon, {
                isKey,
            });
            let typeSql = rendered.sql;
            const typeNotes = [col.typeNote, rendered.note].filter(
                Boolean
            ) as string[];
            typeNotes.forEach((n) => notes.add(SECTION.type, where(field), n));
            if (rendered.general)
                notes.add(SECTION.type, undefined, rendered.general);
            columnTypes.set(field.id, typeSql);

            // --- auto numbering
            let autoSql = '';
            let inlinePk = false;
            if (col.auto) {
                const reason = autoProblem(col, typeSql, field);
                if (reason) {
                    notes.add(
                        SECTION.auto,
                        where(field),
                        `${reason}; the column is not numbered automatically`
                    );
                } else if (target === 'postgresql') {
                    typeSql =
                        {
                            smallint: 'smallserial',
                            integer: 'serial',
                            bigint: 'bigserial',
                        }[typeSql] ?? typeSql;
                } else if (target === 'mysql') {
                    autoSql = ' AUTO_INCREMENT';
                } else if (target === 'sqlserver') {
                    autoSql = ' IDENTITY(1,1)';
                } else if (target === 'sqlite') {
                    inlinePk = true;
                }
                if (!reason) autoUsed = true;
            }
            const auto =
                autoSql !== '' ||
                inlinePk ||
                (target === 'postgresql' && /serial$/.test(typeSql));

            // --- default
            let defaultSql = '';
            if (field.default && !auto) {
                const parsed = parseDefault(field.default);
                if (parsed.kind !== 'auto') {
                    const d = renderDefault(
                        parsed,
                        col.canon,
                        rendered,
                        target
                    );
                    if (d.sql) defaultSql = ` DEFAULT ${d.sql}`;
                    if (d.note)
                        notes.add(SECTION.default, where(field), d.note);
                    if (
                        parsed.kind === 'uuid' &&
                        target === 'sqlite' &&
                        d.sql
                    ) {
                        notes.add(
                            SECTION.default,
                            where(field),
                            'UUID generated with a SQLite expression, as SQLite has no UUID function'
                        );
                    }
                }
            }

            const isPk = field.primaryKey;
            const notNull = isPk || auto || !field.nullable;
            const nullSql = notNull
                ? ' NOT NULL'
                : target === 'sqlserver'
                  ? ' NULL'
                  : '';
            const uniqueSql =
                field.unique && !(isPk && pk.length === 1) ? ' UNIQUE' : '';
            const commentSql =
                target === 'mysql' && field.comments
                    ? ` COMMENT '${escapeSQLComment(field.comments)}'`
                    : '';
            if (field.comments) {
                if (target === 'postgresql') {
                    columnComments.push(
                        `COMMENT ON COLUMN ${tableRef(table)}.${quote(target, field.name)} IS '${escapeSQLComment(field.comments)}';`
                    );
                }
            }

            let text = `${quote(target, field.name)} ${typeSql}`;
            if (target === 'sqlserver') {
                text += `${autoSql}${nullSql}${uniqueSql}${defaultSql}`;
            } else if (target === 'sqlite' && inlinePk) {
                text += `${nullSql} PRIMARY KEY AUTOINCREMENT${uniqueSql}${defaultSql}`;
                sqliteInlinePk = true;
            } else {
                text += `${nullSql}${autoSql}${uniqueSql}${defaultSql}${commentSql}`;
            }

            const lineComments =
                (target === 'sqlserver' || target === 'sqlite') &&
                field.comments
                    ? field.comments
                          .split('\n')
                          .map((l) => `    -- ${oneLine(l)}\n`)
                          .join('')
                    : '';
            items.push({
                before: lineComments || undefined,
                text,
                comment:
                    typeNotes.length > 0
                        ? `Was: ${oneLine(field.type.name)}`
                        : undefined,
            });

            if (rendered.enumCheck && rendered.enumCheck.length > 0) {
                const list = rendered.enumCheck
                    .map((v) => stringLiteral(target, v, true))
                    .join(', ');
                enumChecks.push(
                    `CHECK (${quote(target, field.name)} IN (${list}))`
                );
            }

            // MySQL wants an index that starts with the numbered column
            if (autoSql && target === 'mysql') {
                const indexed = pkIds[0] === field.id || field.unique;
                if (!indexed) {
                    constraints.push({
                        text: `KEY (${quote(target, field.name)})`,
                    });
                }
            }
        }

        // --- primary key
        if (pk.length > 0 && !sqliteInlinePk) {
            constraints.unshift({
                text: `PRIMARY KEY (${pk.map((f) => quote(target, f.name)).join(', ')})`,
            });
        }

        // --- checks
        const columnCanons = new Map<string, Canon>(
            table.fields.map((f) => [
                f.name.toLowerCase(),
                columns.get(f.id)!.canon,
            ])
        );
        enumChecks.forEach((text) => constraints.push({ text }));
        for (const check of table.checkConstraints ?? []) {
            if (!check.expression?.trim()) continue;
            const result = convertCheck(
                check.expression,
                source,
                target,
                columnCanons
            );
            if (result.ok) {
                constraints.push({ text: `CHECK (${result.sql})` });
            } else {
                notes.add(
                    SECTION.constraint,
                    table.name,
                    `CHECK (${oneLine(check.expression)}) not created: it uses ${result.reason}`
                );
                after.push(
                    `-- not created (uses ${result.reason}): CHECK (${oneLine(check.expression)})`
                );
            }
        }

        // --- foreign keys, inline for SQLite
        for (const k of keysUsable.filter((x) => x.fkTable.id === table.id)) {
            if (target === 'sqlite') constraints.push({ text: fkSql(k, true) });
        }
        if (target === 'sqlite') {
            for (const k of foreignKeys.filter(
                (x) => x.fkTable.id === table.id && x.problem
            )) {
                after.push(
                    `-- not created (${k.problem}): FOREIGN KEY (${k.fkFields.map((f) => f.name).join(', ')}) -> ${k.refTable.name}`
                );
            }
        }

        const lines = [...items, ...constraints];
        const body = lines
            .map((it, i) => {
                const comma = i < lines.length - 1 ? ',' : '';
                const tail = it.comment ? ` -- ${it.comment}` : '';
                return `${it.before ?? ''}    ${it.text}${comma}${tail}`;
            })
            .join('\n');

        let out = '';
        if (table.comments && (target === 'sqlserver' || target === 'sqlite')) {
            out += `${table.comments
                .split('\n')
                .map((l) => `-- ${oneLine(l)}`)
                .join('\n')}\n`;
        }
        const tableComment =
            target === 'mysql' && table.comments
                ? ` COMMENT='${escapeSQLComment(table.comments)}'`
                : '';
        out += `CREATE TABLE ${tableRef(table)} (\n${body}\n)${tableComment};\n`;
        if (target === 'postgresql' && table.comments) {
            out += `COMMENT ON TABLE ${tableRef(table)} IS '${escapeSQLComment(table.comments)}';\n`;
        }
        if (columnComments.length > 0) out += `${columnComments.join('\n')}\n`;
        if (after.length > 0) out += `${after.join('\n')}\n`;

        // --- indexes
        const indexes = planIndexes(table, pkIds);
        if (indexes.length > 0) out += `\n-- Indexes\n${indexes.join('\n')}\n`;
        return out;

        function autoProblem(
            col: Column,
            typeSql: string,
            field: DBField
        ): string | null {
            if (col.canon.kind !== 'int')
                return 'auto numbering needs an integer column';
            if (target === 'postgresql') {
                return ['smallint', 'integer', 'bigint'].includes(typeSql)
                    ? null
                    : 'the column is too large for PostgreSQL auto numbering';
            }
            if (autoUsed)
                return `${DATABASE_LABEL[targetDatabaseType]} numbers only one column per table`;
            if (target === 'sqlite') {
                return sqliteAutoField?.id === field.id
                    ? null
                    : 'SQLite can only number a column that is the whole primary key';
            }
            return null;
        }
    }

    function planIndexes(table: DBTable, pkIds: string[]): string[] {
        const out: string[] = [];
        for (const index of table.indexes) {
            if (index.isPrimaryKey) continue;
            const fields = index.fieldIds
                .map((id) => table.fields.find((f) => f.id === id))
                .filter((f): f is DBField => !!f);
            if (fields.length === 0) continue;
            // an index on exactly the primary key adds nothing
            if (
                pkIds.length > 0 &&
                sameSet(
                    fields.map((f) => f.id),
                    pkIds
                )
            ) {
                continue;
            }
            const type = (index.type ?? '').toLowerCase();
            if (
                [
                    'hash',
                    'gin',
                    'gist',
                    'spgist',
                    'brin',
                    'fulltext',
                    'spatial',
                    'xml',
                ].includes(type)
            ) {
                notes.add(
                    SECTION.index,
                    `${table.name}.${index.name}`,
                    `${type} index created as a regular index`
                );
            }
            const base =
                index.name?.trim() ||
                `idx_${table.name}_${fields.map((f) => f.name).join('_')}`;
            const name = unique(base, `_${table.name}`);
            out.push(
                `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${quote(target, name)} ON ${tableRef(table)} (${fields.map((f) => quote(target, f.name)).join(', ')});`
            );
        }
        return out.sort((a, b) => a.localeCompare(b));
    }
}
