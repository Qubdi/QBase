import { describe, expect, it } from 'vitest';
import { DatabaseType } from '@/qbase/diagram-types';
import { DBCustomTypeKind } from '@/qbase/diagram-types';
import { exportDiagramSql } from '@/qbase/sql-adapters';
import {
    diagram,
    exportBaseSQL,
    field,
    pk,
    relationship,
    shop,
    table,
} from './builders';

const convert = (d: ReturnType<typeof diagram>, target: DatabaseType) =>
    exportBaseSQL({
        diagram: d,
        targetDatabaseType: target,
    });

const { MYSQL, MARIADB, POSTGRESQL, SQL_SERVER, SQLITE } = DatabaseType;

describe('converting a diagram between databases', () => {
    describe('MySQL to PostgreSQL', () => {
        const mysql = shop(MYSQL).diagram;
        const sql = convert(mysql, POSTGRESQL);

        it('numbers the key, keeps the default and the unique column', () => {
            expect(sql).toContain('"id" serial NOT NULL');
            expect(sql).toContain('"email" varchar(255) NOT NULL UNIQUE');
            expect(sql).toContain(
                '"created_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP'
            );
            expect(sql).toContain('PRIMARY KEY ("id")');
        });

        it('adds the foreign key afterwards', () => {
            expect(sql).toContain(
                'ALTER TABLE "orders" ADD CONSTRAINT "fk_orders_customer" FOREIGN KEY ("customer_id") REFERENCES "customers" ("id");'
            );
        });

        it('starts with a header that names both databases', () => {
            expect(
                sql.startsWith(
                    '-- MySQL to PostgreSQL conversion\n-- Generated by QBase\n'
                )
            ).toBe(true);
        });

        it('has no notes when nothing was approximated', () => {
            expect(sql).not.toContain('CONVERSION NOTES');
        });
    });

    describe('SQL Server to MySQL', () => {
        it('numbers with AUTO_INCREMENT and converts what is SQL Server only', () => {
            const t = table('t', [
                pk('id', 'int', { increment: true }),
                field('guid', 'uniqueidentifier', { default: '(newid())' }),
                field('paid', 'bit', { nullable: false, default: '((0))' }),
                field('note', 'nvarchar', { characterMaximumLength: '-1' }),
                field('amount', 'money'),
                field('at', 'datetimeoffset'),
            ]);
            const sql = convert(diagram(SQL_SERVER, [t]), MYSQL);
            expect(sql).toContain('`id` INT NOT NULL AUTO_INCREMENT');
            expect(sql).toContain('`guid` CHAR(36) DEFAULT (UUID())');
            expect(sql).toContain('`paid` TINYINT(1) NOT NULL DEFAULT 0');
            expect(sql).toContain('`note` LONGTEXT');
            expect(sql).toContain('`amount` DECIMAL(19, 4), -- Was: money');
            expect(sql).toContain('t.amount: money converted to a fixed-point');
        });

        it('flags a time zone type that MySQL can only approximate', () => {
            const t = table('t', [
                pk('id', 'int'),
                field('at', 'datetimeoffset'),
            ]);
            const sql = convert(diagram(SQL_SERVER, [t]), MYSQL);
            expect(sql).toContain('`at` DATETIME, -- Was: datetimeoffset');
            expect(sql).toContain('t.at: time zone is lost');
        });

        it('drops the dbo schema, which MySQL does not have', () => {
            const t = table('users', [pk('id', 'int')], { schema: 'dbo' });
            const sql = convert(diagram(SQL_SERVER, [t]), MYSQL);
            expect(sql).toContain('CREATE TABLE `users`');
            expect(sql).not.toContain('dbo');
        });
    });

    describe('to SQLite', () => {
        it('keeps a numbered primary key as INTEGER PRIMARY KEY AUTOINCREMENT, inline', () => {
            const sql = convert(shop(MYSQL).diagram, SQLITE);
            expect(sql).toContain(
                '"id" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT'
            );
            // an inline primary key is the whole key: no second one
            expect(sql.match(/PRIMARY KEY/g)).toHaveLength(2);
            expect(sql).not.toMatch(/PRIMARY KEY \("id"\)/);
        });

        it('puts the foreign keys inside CREATE TABLE, as SQLite has no ALTER ... ADD CONSTRAINT', () => {
            const sql = convert(shop(MYSQL).diagram, SQLITE);
            expect(sql).toContain(
                'FOREIGN KEY ("customer_id") REFERENCES "customers" ("id")'
            );
            expect(sql).not.toContain('ALTER TABLE');
        });

        it('cannot number a column that is not the whole primary key, and says so', () => {
            const t = table('t', [
                pk('a', 'int'),
                pk('b', 'int', { increment: true }),
            ]);
            const sql = convert(diagram(MYSQL, [t]), SQLITE);
            expect(sql).toContain('PRIMARY KEY ("a", "b")');
            expect(sql).not.toContain('AUTOINCREMENT');
            expect(sql).toContain(
                't.b: only the whole primary key can be numbered in SQLite'
            );
        });

        it('prefixes the schema to the table name, as SQLite has no schemas', () => {
            const t = table('items', [pk('id', 'int')], { schema: 'shop' });
            const sql = convert(diagram(SQL_SERVER, [t]), SQLITE);
            expect(sql).toContain('CREATE TABLE "shop_items"');
            expect(sql).toContain('SQLite has no schemas');
        });

        it('says once that decimals are not exact there', () => {
            const t = table('t', [
                field('a', 'decimal', { precision: 5, scale: 2 }),
                field('b', 'decimal', { precision: 9, scale: 4 }),
            ]);
            const sql = convert(diagram(MYSQL, [t]), SQLITE);
            expect(sql.match(/NUMERIC affinity/g)).toHaveLength(1);
        });
    });

    describe('foreign keys', () => {
        it('puts the parts of a composite key back together', () => {
            const lines = table('lines', [
                pk('order_id', 'int'),
                pk('no', 'int'),
            ]);
            const notes = table('notes', [
                pk('id', 'int'),
                field('order_id', 'int'),
                field('no', 'int'),
            ]);
            const d = diagram(
                MYSQL,
                [lines, notes],
                [
                    relationship(
                        'fk_a',
                        [lines, lines.fields[0]],
                        [notes, notes.fields[1]]
                    ),
                    relationship(
                        'fk_a',
                        [lines, lines.fields[1]],
                        [notes, notes.fields[2]]
                    ),
                ]
            );
            const sql = convert(d, POSTGRESQL);
            expect(sql).toContain(
                'ADD CONSTRAINT "fk_a" FOREIGN KEY ("order_id", "no") REFERENCES "lines" ("order_id", "no")'
            );
            expect(sql.match(/FOREIGN KEY/g)).toHaveLength(1);
        });

        it('leaves out a foreign key to a column that is not unique, and says why', () => {
            const parent = table('parent', [field('code', 'varchar')]);
            const child = table('child', [
                pk('id', 'int'),
                field('code', 'varchar'),
            ]);
            const d = diagram(
                MYSQL,
                [parent, child],
                [
                    relationship(
                        'fk_child',
                        [parent, parent.fields[0]],
                        [child, child.fields[1]]
                    ),
                ]
            );
            const sql = convert(d, POSTGRESQL);
            expect(sql).not.toMatch(/ALTER TABLE .* FOREIGN KEY/);
            expect(sql).toContain('-- not created (parent.code is not unique');
            expect(sql).toContain('not created: parent.code is not unique');
        });

        it('gives a key column the size of the column it points at', () => {
            const parent = table('parent', [pk('id', 'bigint')]);
            const child = table('child', [
                pk('id', 'int'),
                field('parent_id', 'int'),
            ]);
            const d = diagram(
                MYSQL,
                [parent, child],
                [
                    relationship(
                        'fk',
                        [parent, parent.fields[0]],
                        [child, child.fields[1]]
                    ),
                ]
            );
            const sql = convert(d, SQL_SERVER);
            expect(sql).toContain('[parent_id] BIGINT NULL');
            expect(sql).toContain(
                'child.parent_id: changed to match parent.id'
            );
        });

        it('turns a leftover many-to-many into a normal foreign key', () => {
            const parent = table('parent', [pk('id', 'int')]);
            const child = table('child', [
                pk('id', 'int'),
                field('parent_id', 'int'),
            ]);
            const d = diagram(
                MYSQL,
                [parent, child],
                [
                    relationship(
                        'fk',
                        [parent, parent.fields[0]],
                        [child, child.fields[1]],
                        {
                            sourceCardinality: 'many',
                            targetCardinality: 'many',
                        }
                    ),
                ]
            );
            expect(convert(d, POSTGRESQL)).toContain(
                'ALTER TABLE "child" ADD CONSTRAINT "fk" FOREIGN KEY ("parent_id") REFERENCES "parent" ("id")'
            );
        });
    });

    describe('columns that are part of a key', () => {
        const keyed = (types: { str: string }) =>
            table('t', [
                pk('code', types.str),
                field('label', types.str, { unique: true }),
            ]);

        it('are limited where MySQL or SQL Server cannot index the unlimited kind', () => {
            const pg = diagram(POSTGRESQL, [keyed({ str: 'text' })]);
            const mysql = convert(pg, MYSQL);
            expect(mysql).toContain('`code` VARCHAR(768) NOT NULL');
            expect(mysql).toContain('`label` VARCHAR(768) UNIQUE');
            expect(mysql).toContain('shortened to 768 characters');
            expect(convert(pg, SQL_SERVER)).toContain(
                '[code] NVARCHAR(450) NOT NULL'
            );
        });

        it('are left alone for PostgreSQL and SQLite', () => {
            const mysqlSource = diagram(MYSQL, [keyed({ str: 'text' })]);
            expect(convert(mysqlSource, POSTGRESQL)).toContain(
                '"code" text NOT NULL'
            );
            expect(convert(mysqlSource, SQLITE)).toContain(
                '"code" TEXT NOT NULL'
            );
        });
    });

    describe('enums, arrays and composite types', () => {
        const pg = (col: ReturnType<typeof field>, extra = {}) =>
            diagram(
                POSTGRESQL,
                [table('t', [pk('id', 'int'), col])],
                [],
                extra
            );
        const status = {
            id: 'e',
            name: 'status',
            schema: 'public',
            kind: DBCustomTypeKind.enum,
            values: ['new', 'paid'],
        };

        it('keeps an enum for MySQL and enforces it with a CHECK elsewhere', () => {
            const d = pg(field('s', 'status'), { customTypes: [status] });
            expect(convert(d, MYSQL)).toContain("`s` ENUM('new', 'paid')");
            const sqlite = convert(d, SQLITE);
            expect(sqlite).toContain('"s" TEXT');
            expect(sqlite).toContain(`CHECK ("s" IN ('new', 'paid'))`);
            expect(convert(d, SQL_SERVER)).toContain(
                `CHECK ([s] IN (N'new', N'paid'))`
            );
        });

        it('stores an array as JSON text where there is no array type', () => {
            const d = pg(
                field('tags', 'text', {
                    isArray: true,
                    default: "'{}'::text[]",
                })
            );
            const sql = convert(d, MYSQL);
            expect(sql).toContain("`tags` JSON DEFAULT ('[]')");
            expect(sql).toContain('t.tags: text is an array');
        });

        it('stores a composite type as JSON, and says so', () => {
            const d = pg(field('home', 'address'), {
                customTypes: [
                    {
                        id: 'c',
                        name: 'address',
                        kind: DBCustomTypeKind.composite,
                        fields: [{ field: 'street', type: 'text' }],
                    },
                ],
            });
            expect(convert(d, MYSQL)).toContain('`home` JSON');
            expect(convert(d, MYSQL)).toContain('composite type');
        });
    });

    describe('constraints and indexes', () => {
        it('converts a CHECK it understands and reports the rest', () => {
            const t = table('t', [
                pk('id', 'int'),
                field('qty', 'int'),
                field('sku', 'varchar'),
            ]);
            t.checkConstraints = [
                { id: 'c1', expression: '((qty > 0))', createdAt: 1 },
                { id: 'c2', expression: "((sku)::text ~ '^a')", createdAt: 1 },
            ];
            const sql = convert(diagram(POSTGRESQL, [t]), MYSQL);
            expect(sql).toContain('CHECK (`qty` > 0)');
            expect(sql).toContain('-- not created (uses the symbol :)');
            expect(sql).toContain("CHECK (((sku)::text ~ '^a')) not created");
        });

        it('makes an index, and says when its type is not available', () => {
            const t = table('t', [
                pk('id', 'int'),
                field('doc', 'varchar', { characterMaximumLength: '50' }),
            ]);
            t.indexes = [
                {
                    id: 'i',
                    name: 'idx_doc',
                    unique: false,
                    fieldIds: [t.fields[1].id],
                    createdAt: 1,
                    type: 'gin',
                },
            ];
            const sql = convert(diagram(POSTGRESQL, [t]), SQLITE);
            expect(sql).toContain('CREATE INDEX "idx_doc" ON "t" ("doc");');
            expect(sql).toContain(
                't.idx_doc: gin index created as a regular index'
            );
        });

        it('gives colliding index names a number, since PostgreSQL and SQLite share one namespace', () => {
            const a = table('a', [pk('id', 'int'), field('x', 'int')]);
            const b = table('b', [pk('id', 'int'), field('x', 'int')]);
            a.indexes = [
                {
                    id: 'i1',
                    name: 'idx_x',
                    unique: false,
                    fieldIds: [a.fields[1].id],
                    createdAt: 1,
                },
            ];
            b.indexes = [
                {
                    id: 'i2',
                    name: 'idx_x',
                    unique: true,
                    fieldIds: [b.fields[1].id],
                    createdAt: 1,
                },
            ];
            const sql = convert(diagram(MYSQL, [a, b]), POSTGRESQL);
            expect(sql).toContain('CREATE INDEX "idx_x" ON "a" ("x");');
            expect(sql).toContain(
                'CREATE UNIQUE INDEX "idx_x_b_2" ON "b" ("x");'
            );
        });

        it('skips an index that is just the primary key', () => {
            const t = table('t', [pk('id', 'int')]);
            t.indexes = [
                {
                    id: 'i',
                    name: 'idx_id',
                    unique: true,
                    fieldIds: [t.fields[0].id],
                    createdAt: 1,
                },
            ];
            expect(convert(diagram(MYSQL, [t]), POSTGRESQL)).not.toContain(
                'CREATE UNIQUE INDEX'
            );
        });
    });

    describe('comments, views and odd tables', () => {
        it('writes comments the way each database takes them', () => {
            const t = table('t', [pk('id', 'int', { comments: 'the key' })], {
                comments: "it's a table",
            });
            const d = diagram(MYSQL, [t]);
            expect(convert(d, POSTGRESQL)).toContain(
                `COMMENT ON COLUMN "t"."id" IS 'the key';`
            );
            expect(convert(d, POSTGRESQL)).toContain(
                `COMMENT ON TABLE "t" IS 'it''s a table';`
            );
            const mssql = convert(d, SQL_SERVER);
            expect(mssql).toContain('-- the key');
            expect(mssql).toContain("-- it's a table");
            const pgToMysql = convert(diagram(POSTGRESQL, [t]), MYSQL);
            expect(pgToMysql).toContain("COMMENT 'the key'");
            expect(pgToMysql).toContain(`COMMENT='it''s a table'`);
        });

        it('leaves out views, and says how many', () => {
            const view = table('v', [field('a', 'int')], { isView: true });
            const sql = convert(
                diagram(MYSQL, [table('t', [pk('id', 'int')]), view]),
                POSTGRESQL
            );
            expect(sql).not.toContain('"v"');
            expect(sql).toContain('1 view not exported');
        });

        it('leaves out a table with no columns, and says so', () => {
            const sql = convert(
                diagram(MYSQL, [
                    table('empty', [pk('id', 'int')]),
                    table('hollow', []),
                ]),
                POSTGRESQL
            );
            expect(sql).toContain('CREATE TABLE "empty"');
            expect(sql).not.toContain('"hollow"');
            expect(sql).toContain(
                'hollow: not exported: the table has no columns'
            );
        });

        it('makes a schema, or a database for MySQL', () => {
            const t = table('t', [pk('id', 'int')], { schema: 'sales' });
            expect(convert(diagram(SQL_SERVER, [t]), POSTGRESQL)).toContain(
                'CREATE SCHEMA IF NOT EXISTS "sales";'
            );
            expect(convert(diagram(SQL_SERVER, [t]), POSTGRESQL)).toContain(
                'CREATE TABLE "sales"."t"'
            );
            expect(convert(diagram(SQL_SERVER, [t]), MYSQL)).toContain(
                'CREATE DATABASE IF NOT EXISTS `sales`;'
            );
            expect(convert(diagram(POSTGRESQL, [t]), SQL_SERVER)).toContain(
                "EXEC('CREATE SCHEMA [sales]')"
            );
        });

        it('treats the source default schema as no schema', () => {
            const t = table('t', [pk('id', 'int')], { schema: 'public' });
            const sql = convert(diagram(POSTGRESQL, [t]), SQL_SERVER);
            expect(sql).toContain('CREATE TABLE [t]');
            expect(sql).not.toContain('public');
        });

        it('says when a table or column name is longer than the target keeps', () => {
            const long = 'x'.repeat(70);
            const t = table(long, [pk('id', 'int'), field(long, 'int')]);
            const mysql = convert(diagram(SQL_SERVER, [t]), MYSQL);
            expect(mysql).toContain(
                `${long}: table name is longer than 64 characters, the limit of MySQL`
            );
            expect(mysql).toContain(
                `${long}: column name is longer than 64 characters, the limit of MySQL`
            );
            expect(convert(diagram(MYSQL, [t]), POSTGRESQL)).toContain(
                'table name is longer than 63 characters, the limit of PostgreSQL'
            );
            // SQL Server and SQLite take it
            expect(convert(diagram(MYSQL, [t]), SQL_SERVER)).not.toContain(
                'Names:'
            );
            expect(convert(diagram(MYSQL, [t]), SQLITE)).not.toContain(
                'Names:'
            );
        });

        it('explains why an auto numbered column cannot be numbered', () => {
            const t = table('t', [pk('id', 'varchar', { increment: true })]);
            const sql = convert(diagram(MYSQL, [t]), POSTGRESQL);
            expect(sql).not.toContain('serial');
            expect(sql).toContain(
                't.id: not an integer column: the column is not numbered'
            );
        });

        it('numbers only one column per table where the database allows one', () => {
            const t = table('t', [
                pk('a', 'int', { increment: true }),
                field('b', 'int', { increment: true, unique: true }),
            ]);
            const mysql = convert(diagram(POSTGRESQL, [t]), MYSQL);
            expect(mysql.match(/AUTO_INCREMENT/g)).toHaveLength(1);
            expect(mysql).toContain(
                't.b: only one column per table can be numbered in MySQL'
            );
            // PostgreSQL has no such limit
            expect(
                convert(diagram(MYSQL, [t]), POSTGRESQL).match(/serial/g)
            ).toHaveLength(2);
        });

        it('adds the key MySQL wants on a numbered column that is not the first of the key', () => {
            const t = table('t', [
                pk('a', 'int'),
                pk('b', 'int', { increment: true }),
            ]);
            expect(convert(diagram(POSTGRESQL, [t]), MYSQL)).toContain(
                'KEY (`b`)'
            );
        });
    });

    describe('the diagram is left alone', () => {
        it('does not change anything it was given', () => {
            const d = shop(MYSQL).diagram;
            const before = JSON.stringify(d);
            for (const target of [POSTGRESQL, SQL_SERVER, SQLITE, MARIADB])
                convert(d, target);
            expect(JSON.stringify(d)).toBe(before);
        });
    });
});

describe('which pairs have a converter', () => {
    const sql = (source: DatabaseType, target: DatabaseType) =>
        exportDiagramSql({
            diagram: diagram(source, [table('t', [pk('id', 'int')])]),
            targetDatabaseType: target,
        });

    it('covers every pair between the five databases, generic SQL and CockroachDB', () => {
        const sources = [
            POSTGRESQL,
            MYSQL,
            MARIADB,
            SQL_SERVER,
            SQLITE,
            DatabaseType.GENERIC,
            DatabaseType.COCKROACHDB,
        ];
        for (const source of sources) {
            for (const target of [
                POSTGRESQL,
                MYSQL,
                MARIADB,
                SQL_SERVER,
                SQLITE,
            ]) {
                const result = sql(source, target);
                expect(
                    result.diagnostics.filter((d) => d.severity === 'error'),
                    `${source} to ${target}`
                ).toEqual([]);
                expect(result.text, `${source} to ${target}`).toContain(
                    'CREATE TABLE'
                );
            }
        }
    });

    it('uses the generic generator for Oracle and ClickHouse, and has none to generic SQL (EXP-008)', () => {
        for (const [source, target] of [
            [DatabaseType.ORACLE, POSTGRESQL],
            [DatabaseType.CLICKHOUSE, MYSQL],
        ] as const) {
            const result = sql(source, target);
            expect(result.text).toContain('-- WARNING: there is no converter');
            expect(result.text).toContain('CREATE TABLE');
        }
        const result = sql(MYSQL, DatabaseType.GENERIC);
        expect(result.text).toBe('');
        expect(result.diagnostics[0]).toMatchObject({
            severity: 'error',
            message: expect.stringContaining('SQL export is not supported'),
        });
    });
});

describe('exporting SQL', () => {
    const d = () => shop(MYSQL).diagram;

    it.each([
        [POSTGRESQL, 'PostgreSQL'],
        [SQL_SERVER, 'SQL Server'],
        [SQLITE, 'SQLite'],
    ])('converts a MySQL diagram for %s', (target, label) => {
        expect(
            exportBaseSQL({ diagram: d(), targetDatabaseType: target })
        ).toMatch(new RegExp(`^-- (MySQL|MariaDB) to ${label} conversion`));
    });

    it('converts a PostgreSQL diagram for MySQL, MariaDB and SQL Server with the same converter', () => {
        const pg = shop(POSTGRESQL, {
            int: 'integer',
            str: 'varchar',
            ts: 'timestamp',
        }).diagram;
        for (const [target, label] of [
            [MYSQL, 'MySQL'],
            [MARIADB, 'MariaDB'],
            [SQL_SERVER, 'SQL Server'],
        ] as const) {
            expect(
                exportBaseSQL({ diagram: pg, targetDatabaseType: target })
            ).toMatch(new RegExp(`^-- PostgreSQL to ${label} conversion`));
        }
    });

    it('uses the diagram database itself, with no conversion, for its own type', () => {
        const sql = exportBaseSQL({ diagram: d(), targetDatabaseType: MYSQL });
        expect(sql).not.toContain('conversion');
    });

    it('treats a MySQL diagram as already valid MariaDB', () => {
        const sql = exportBaseSQL({
            diagram: d(),
            targetDatabaseType: MARIADB,
        });
        expect(sql).not.toContain('conversion');
        expect(sql).toContain('CREATE TABLE');
    });

    it('does not change the diagram that is open in the editor, even when a foreign key type is adjusted', () => {
        const parent = table('parent', [pk('id', 'bigint')]);
        const child = table('child', [
            pk('id', 'int'),
            field('parent_id', 'int'),
        ]);
        const oracle = diagram(
            DatabaseType.ORACLE,
            [parent, child],
            [
                relationship(
                    'fk',
                    [parent, parent.fields[0]],
                    [child, child.fields[1]]
                ),
            ]
        );
        const before = JSON.stringify(oracle);
        exportBaseSQL({ diagram: oracle, targetDatabaseType: POSTGRESQL });
        expect(JSON.stringify(oracle)).toBe(before);
    });
});
